-- Company directory, second copy (told 2026-10-29). Academy keeps the mirror
-- that its own screens read; Holding OS reaches only this project through its
-- proxy, so RNB → Settings → Company Directory reads this table. The worker
-- writes both in the same hourly pass from the workbook (worker/directory-rnb.ts).
-- Read-only for people: the workbook is the master.

create table onboarding.directory_people (
  id             bigint generated by default as identity primary key,
  category       text not null default 'employee'
                 check (category in ('employee', 'subcontractor', 'vendor', 'installer')),
  section        text not null,
  job_title      text,
  full_name      text not null,
  phone          text,
  office         text,
  email          text,
  birthday_month smallint check (birthday_month between 1 and 12),
  birthday_day   smallint check (birthday_day between 1 and 31),
  start_date     date,
  active         boolean not null default true,
  notes          text,
  sort_order     integer not null default 0,
  source         text not null default 'excel_sync',
  source_key     text not null unique,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index directory_people_list_idx
  on onboarding.directory_people (active, category, section, sort_order);

-- Grants ship with the table: a missing grant is refused before RLS is read.
alter table onboarding.directory_people enable row level security;
create policy directory_people_read on onboarding.directory_people
  for select to authenticated using (true);
grant select on onboarding.directory_people to authenticated;
grant select, insert, update, delete on onboarding.directory_people to service_role;
grant usage, select on sequence onboarding.directory_people_id_seq to service_role;

-- "Open the workbook" in the Settings tab.
insert into onboarding.app_settings (key, value) values
  ('company_directory_web_url',
