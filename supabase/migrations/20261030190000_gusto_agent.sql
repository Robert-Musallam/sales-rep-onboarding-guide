-- ============================================================================
-- Gusto onboarding agent (Phase 3) — state, run log, settings.
-- ============================================================================
-- The browser agent (gusto-agent/, Mac mini) adds a rep to the right Gusto
-- company and sends the Gusto invite once the rep reaches info_submitted.
-- Its state lives in NEW columns (gusto_agent_*) so the existing, manually
-- edited reps.gusto_status keeps its meaning.
--
-- gusto_agent_status lifecycle:
--   null           not seen by the agent yet (only these are ever picked up)
--   legacy         was past invited when this migration ran → never swept
--   manual         territory not in gusto_agent_territories (⚠️ legal) → ops adds by hand
--   queued         claimed by the worker sweep, outbox row created
--   in_progress    run.sh started
--   dry_run_ok     dry mode: form filled, nothing saved
--   added          invite sent in Gusto
--   stopped        a stop rule fired (stop reason in gusto_agent_note)
--   needs_review   run crashed / in_progress > 45 min — NEVER auto-retried
--                  (a crash after the invite click would double-invite)
-- Re-arming a rep (e.g. after dry_run_ok, to go live) is an explicit
--   update onboarding.reps set gusto_agent_status = null where id = …;
-- ============================================================================

alter table onboarding.reps
  add column if not exists gusto_agent_status  text,
  add column if not exists gusto_agent_company text,
  add column if not exists gusto_agent_at      timestamptz,
  add column if not exists gusto_agent_note    text;

create index if not exists reps_gusto_agent_pick_idx
  on onboarding.reps (status) where gusto_agent_status is null;

-- Existing reps are history, not work: only reps that reach info_submitted
-- after this migration are picked up. Invited reps stay null on purpose.
update onboarding.reps
   set gusto_agent_status = 'legacy'
 where gusto_agent_status is null
   and status <> 'invited';

-- One row per agent run (append-only audit).
create table if not exists onboarding.gusto_agent_runs (
  id              bigint generated by default as identity primary key,
  rep_id          bigint references onboarding.reps (id) on delete set null,
  mode            text not null check (mode in ('dry_run', 'send')),
  outcome         text not null,              -- dry_run_ok | added | stopped | needs_review | session | deferred
  stop_reason     text,
  gusto_company   text,
  invite_sent     boolean not null default false,
  documents       jsonb not null default '[]'::jsonb,
  cost_usd        numeric(8, 4),
  duration_ms     integer,
  result          jsonb,                      -- the skill's JSON result, verbatim
  created_at      timestamptz not null default now()
);
create index if not exists gusto_agent_runs_rep_idx on onboarding.gusto_agent_runs (rep_id, created_at desc);

alter table onboarding.gusto_agent_runs enable row level security;
drop policy if exists gusto_agent_runs_all on onboarding.gusto_agent_runs;
create policy gusto_agent_runs_all on onboarding.gusto_agent_runs
  for all to authenticated using (true) with check (true);
grant select, insert, update, delete on onboarding.gusto_agent_runs to authenticated, service_role;

