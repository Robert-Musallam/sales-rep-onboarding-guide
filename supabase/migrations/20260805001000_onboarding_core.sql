create trigger trg_reps_updated_at before update on onboarding.reps
  for each row execute function shared.set_updated_at();
create index reps_status_idx on onboarding.reps (status);
create index reps_territory_idx on onboarding.reps (territory_id);

-- Per-rep instantiated checklist.
create table onboarding.checklist_items (
  id             bigint generated by default as identity primary key,
  rep_id         bigint not null references onboarding.reps (id) on delete cascade,
  template_key   text not null references onboarding.checklist_templates (key),
  label          text not null,
  sort_order     int not null,
  automation_key text,
  status         onboarding.item_status not null default 'pending',
  completed_by   uuid references shared.profiles (id),
  completed_at   timestamptz,
  notes          text,
  unique (rep_id, template_key)
);
create index checklist_items_rep_idx on onboarding.checklist_items (rep_id, sort_order);

-- ── Outbox — the ONLY path to external side effects ─────────────────────────
-- API routes insert rows; the worker (mac mini, launchd, 60s) executes them via
-- lib/connectors with the gate stack (dry-run default, kill switch, allowlist).
create table onboarding.outbox (
  id          bigint generated by default as identity primary key,
  action_type text not null,                  -- dispatch key, e.g. 'sms.send', 'm365.create_user'
  rep_id      bigint references onboarding.reps (id) on delete set null,
  payload     jsonb not null default '{}'::jsonb,
  state       onboarding.outbox_state not null default 'pending',
  attempts    int not null default 0,
  last_error  text,
  dedupe_key  text unique,                    -- idempotency across re-enqueues; null = no dedupe
  run_after   timestamptz not null default now(),
  created_at  timestamptz not null default now(),
  executed_at timestamptz,
  dry_run_log jsonb                           -- what WOULD have been sent when gated
);
create index outbox_pending_idx on onboarding.outbox (state, run_after) where state = 'pending';
create index outbox_rep_idx on onboarding.outbox (rep_id, created_at desc);

-- ── Raw form submissions (audit + replay) ───────────────────────────────────
create table onboarding.form_submissions (
  id            bigint generated by default as identity primary key,
  source        text not null,                -- 'jotform_info' | 'native_intake' | …
  form_id       text,
  submission_id text unique,
  rep_id        bigint references onboarding.reps (id) on delete set null,
  payload       jsonb not null default '{}'::jsonb,
  received_at   timestamptz not null default now()
);

-- ── Delegated OAuth token store (Graph chat sends as a real user) ───────────
-- refresh_token_enc is AES-256-GCM encrypted with TOKEN_ENCRYPTION_KEY (env);
-- only the worker and the OAuth callback route touch this table (service role).
create table onboarding.oauth_tokens (
  provider          text primary key,         -- 'microsoft-delegated'
  account_label     text,                     -- upn of the consented account
  refresh_token_enc text not null,
  scopes            text,
  updated_at        timestamptz not null default now()
);
create trigger trg_oauth_tokens_updated_at before update on onboarding.oauth_tokens
  for each row execute function shared.set_updated_at();

-- ── Rep hub links (token auth — reps have no Supabase login) ────────────────
create table onboarding.rep_links (
  id         bigint generated by default as identity primary key,
  rep_id     bigint not null references onboarding.reps (id) on delete cascade,
  token      text not null unique default encode(gen_random_bytes(24), 'hex'),
  active     boolean not null default true,
  created_at timestamptz not null default now(),
  last_seen  timestamptz
);
create index rep_links_rep_idx on onboarding.rep_links (rep_id);

-- ── Compatibility: employee_teams_chats ─────────────────────────────────────
-- The Make "Dialpad" scenario reads public.employee_teams_chats to route sales
-- reporting. If this app is deployed into the SAME project that table already
-- lives in, this create is a no-op; on a fresh project it recreates the shape
-- so the compat writer (outbox action compat.employee_teams_chats) always works.
create table if not exists public.employee_teams_chats (
  id                          bigint generated by default as identity primary key,
  assigned_employee_first_name text,
  assigned_employee_last_name  text,
  assigned_employee_email      text,
  location                     text,
  chat_id                      text,
  phone_room_chat_id           text,
  created_at                   timestamptz not null default now()
);

-- ── RLS + grants (webapp is fully authenticated; worker uses service role) ──
do $$
declare t text;
begin
  foreach t in array array[
    'territories','people','message_templates','app_settings','checklist_templates',
    'reps','checklist_items','outbox','form_submissions','rep_links'
  ] loop
    execute format('alter table onboarding.%I enable row level security', t);
    execute format(
      'create policy %I_all on onboarding.%I for all to authenticated using (true) with check (true)',
      t, t);
    execute format('grant select, insert, update, delete on onboarding.%I to authenticated', t);
    execute format('grant select, insert, update, delete on onboarding.%I to service_role', t);
  end loop;
end $$;

-- oauth_tokens: service_role only — never exposed to the browser session.
alter table onboarding.oauth_tokens enable row level security;
grant select, insert, update, delete on onboarding.oauth_tokens to service_role;

grant usage, select on all sequences in schema onboarding to authenticated, service_role;
