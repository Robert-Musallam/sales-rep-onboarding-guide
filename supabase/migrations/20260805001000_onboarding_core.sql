-- ============================================================================
-- RNB Onboarding — core schema
-- ============================================================================
-- The brain replacing the Make scenario "Add new sales reps in Teams" + the
-- Google Sheet tracker + Jotform checklist. Side effects NEVER fire inline:
-- API routes write onboarding.outbox rows and the mac-mini worker executes
-- them behind send gates (queue-row boundary, inherited from the leasing stack).
-- ============================================================================

-- ── Enums ───────────────────────────────────────────────────────────────────
create type onboarding.rep_status as enum (
  'invited',          -- manager kicked off; welcome/info-form SMS queued
  'info_submitted',   -- rep info form received
  'contract_sent',    -- gusto contract sent (manual step recorded)
  'contract_signed',  -- clear to provision
  'provisioning',     -- accounts being created (M365 / Teams / HCP)
  'active',           -- fully onboarded
  'inactive'          -- abandoned / terminated
);

create type onboarding.item_status as enum ('pending', 'done', 'skipped', 'blocked');

create type onboarding.outbox_state as enum ('pending', 'in_flight', 'done', 'failed', 'skipped');

-- ── Config tables (Settings UI) ─────────────────────────────────────────────
create table onboarding.territories (
  id                  bigint generated by default as identity primary key,
  name                text not null unique,
  active              boolean not null default true,
  -- Teams chat ids the new rep gets added to (post-sales channels etc.)
  post_sales_chat_ids jsonb not null default '[]'::jsonb,
  -- HCP company/org for this territory. The API key itself stays in env:
  -- hcp_api_key_env names the env var the worker reads (keys never live in DB).
  hcp_company_note    text,
  hcp_api_key_env     text,
  gusto_note          text,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);
create trigger trg_territories_updated_at before update on onboarding.territories
  for each row execute function shared.set_updated_at();

-- Internal stakeholders referenced by automations (replaces hardcoded Azure ids
-- in the Make scenario). `roles` drives membership:
--   phone_room_roster        — added to every new rep's Phone Room group chat
--   welcome_email_bcc        — bcc'd on the welcome email
--   business_card_contact    — receives the business-card request email
--   admin_notify             — notified when a rep submits their info form
-- `territories` non-empty limits a role to those territories (e.g. a regional
-- manager only joins Phone Rooms in their region); empty = all territories.
create table onboarding.people (
  id            bigint generated by default as identity primary key,
  full_name     text not null,
  email         text,
  azure_user_id text,
  phone         text,
  roles         text[] not null default '{}',
  territories   text[] not null default '{}',
  active        boolean not null default true,
  notes         text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create trigger trg_people_updated_at before update on onboarding.people
  for each row execute function shared.set_updated_at();

-- Message bodies the automations send — seeded from the captured Make scenario,
-- editable in Settings. Vars use {{snake_case}} tokens rendered by the worker.
create table onboarding.message_templates (
  key         text primary key,
  channel     text not null check (channel in ('sms', 'teams', 'email')),
  subject     text,                -- email only
  body        text not null,
  description text,
  updated_at  timestamptz not null default now()
);
create trigger trg_message_templates_updated_at before update on onboarding.message_templates
  for each row execute function shared.set_updated_at();

-- Simple key/value app settings (welcome-email sender mailbox, company-wide
-- chat id, admin notification email, kill switch mirror, …).
create table onboarding.app_settings (
  key        text primary key,
  value      jsonb not null,
  updated_at timestamptz not null default now()
);
create trigger trg_app_settings_updated_at before update on onboarding.app_settings
  for each row execute function shared.set_updated_at();

-- The checklist template — instantiated per rep on info submission.
-- automation_key names the bundle of outbox actions completion enqueues
-- (resolved in lib/onboarding/automations.ts); null = purely manual step.
create table onboarding.checklist_templates (
  key            text primary key,
  label          text not null,
  sort_order     int not null,
  automation_key text,
  auto           boolean not null default false,  -- completed by the system, not a human
  active         boolean not null default true,
  description    text
);

-- ── Reps ────────────────────────────────────────────────────────────────────
create table onboarding.reps (
  id              bigint generated by default as identity primary key,
  first_name      text not null,
  last_name       text not null,
  personal_email  text,
  phone_e164      text,                       -- +1XXXXXXXXXX
  phone_os        text,                       -- iOS | Android (drives app-download SMS)
  home_address    text,
  zip_code        text,
  dob             date,
  how_heard       text,
  manager_name    text,
  territory_id    bigint references onboarding.territories (id),
  expected_start  date,
  status          onboarding.rep_status not null default 'invited',
  -- provisioning results
  rnb_email           text,
  m365_user_id        text,
  m365_temp_password  text,                   -- surfaced once in drawer; cleared after first login
  teams_chat_id       text,                   -- 1:1 chat with Robert
  phone_room_chat_id  text,
  hcp_employee_id     text,
  hcp_username        text,
  gusto_status        text,
  greensky_status     text,
  training_passed_at  timestamptz,
  -- intake / form linkage
  jotform_info_submission_id text unique,     -- rep-info form submission (prefilled + edited)
  info                jsonb not null default '{}'::jsonb,  -- extra rep-form fields (shirt size, …)
