-- Daily birthday and work-anniversary greetings in Teams (told 2026-10-27).
-- The worker reads Academy's directory mirror once a day and posts one message
-- per person per kind into the chat below. This file adds the record that keeps
-- it from posting twice, the settings the sweep reads, and the two messages.

create table onboarding.directory_greetings (
  id bigint generated by default as identity primary key,
  person_key text not null,                 -- email, or name:<full name> when there is no email
  kind text not null check (kind in ('birthday', 'anniversary')),
  greeted_on date not null,
  chat_id text not null,
  message_id text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  unique (person_key, kind, greeted_on)
);
create index directory_greetings_day_idx on onboarding.directory_greetings (greeted_on desc);

alter table onboarding.directory_greetings enable row level security;
create policy directory_greetings_all on onboarding.directory_greetings
  for all to authenticated using (true) with check (true);
grant select, insert, update, delete on onboarding.directory_greetings to authenticated, service_role;
grant usage, select on sequence onboarding.directory_greetings_id_seq to authenticated, service_role;

